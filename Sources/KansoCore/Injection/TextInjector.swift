import Foundation
import AppKit
import CoreGraphics

/// Errors that can occur during text injection operations.
public enum TextInjectorError: Error, LocalizedError, Sendable, Equatable {
    case emptyText
    case eventCreationFailed
    case targetAppNotFound

    public var errorDescription: String? {
        switch self {
        case .emptyText:
            return "Cannot inject empty or whitespace-only text."
        case .eventCreationFailed:
            return "Failed to synthesize CGEvent keyboard event."
        case .targetAppNotFound:
            return "Target application is not running or invalid."
        }
    }
}

/// A captured snapshot of NSPasteboard items across all data representations.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Item: Sendable, Equatable {
        public let types: [String: Data]

        public init(types: [String: Data]) {
            self.types = types
        }
    }

    public let items: [Item]

    public init(items: [Item] = []) {
        self.items = items
    }

    public var isEmpty: Bool {
        items.isEmpty
    }
}

/// High-reliability text injection engine utilizing NSPasteboard and synthetic Cmd+V keystrokes.
public final class TextInjector: @unchecked Sendable {
    public enum Constants {
        public static let virtualKeyV: CGKeyCode = 0x09 // kVK_ANSI_V
        public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    }

    public let restoreDelayMs: UInt64
    private let pasteboard: NSPasteboard

    public init(
        restoreDelayMs: UInt64 = 200,
        pasteboard: NSPasteboard = .general
    ) {
        self.restoreDelayMs = restoreDelayMs
        self.pasteboard = pasteboard
    }

    /// Captures a complete multi-type snapshot of the general pasteboard.
    public static func captureSnapshot(from pasteboard: NSPasteboard = .general) -> PasteboardSnapshot {
        guard let pbItems = pasteboard.pasteboardItems, !pbItems.isEmpty else {
            return PasteboardSnapshot(items: [])
        }

        var capturedItems: [PasteboardSnapshot.Item] = []
        for item in pbItems {
            var itemData: [String: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    itemData[type.rawValue] = data
                }
            }
            if !itemData.isEmpty {
                capturedItems.append(PasteboardSnapshot.Item(types: itemData))
            }
        }

        return PasteboardSnapshot(items: capturedItems)
    }

    /// Restores a previously captured snapshot if the pasteboard has not been mutated in the interim.
    /// - Parameters:
    ///   - snapshot: The snapshot to restore.
    ///   - expectedChangeCount: Optional changeCount check to avoid overwriting concurrent user copies.
    /// - Returns: True if restored successfully, false if skipped due to concurrency guard.
    @discardableResult
    public static func restoreSnapshot(
        _ snapshot: PasteboardSnapshot,
        to pasteboard: NSPasteboard = .general,
        expectedChangeCount: Int? = nil
    ) -> Bool {
        if let expected = expectedChangeCount, pasteboard.changeCount != expected {
            // User or another application copied something new during the window. Preserve user copy.
            return false
        }

        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else {
            return true
        }

        var newItems: [NSPasteboardItem] = []
        for captured in snapshot.items {
            let item = NSPasteboardItem()
            for (typeRaw, data) in captured.types {
                item.setData(data, forType: NSPasteboard.PasteboardType(typeRaw))
            }
            newItems.append(item)
        }

        pasteboard.writeObjects(newItems)
        return true
    }

    /// Stages transient text on the pasteboard, tagged to prevent clipboard history pollution.
    public func stageTransientText(_ text: String) -> Int {
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Tag with standard transient types to prevent Raycast, Maccy, Alfred from recording temporary dictations
        item.setData(Data(), forType: Constants.transientType)
        item.setData(Data(), forType: Constants.autoGeneratedType)

        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Synthesizes Cmd+V (paste) keystroke event.
    public func postPasteKeystroke() throws {
        guard let source = CGEventSource(stateID: .combinedSessionState) else {
            throw TextInjectorError.eventCreationFailed
        }

        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: Constants.virtualKeyV, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: Constants.virtualKeyV, keyDown: false) else {
            throw TextInjectorError.eventCreationFailed
        }

        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand

        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }

    /// Injects text into the frontmost application while safely backing up and restoring clipboard.
    /// - Parameters:
    ///   - text: The dictated transcription string to paste.
    ///   - targetApp: Optional running application to ensure focus before pasting.
    public func inject(text: String, targetApp: NSRunningApplication? = nil) async throws {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else {
            throw TextInjectorError.emptyText
        }

        // 1. Capture user's current clipboard
        let snapshot = Self.captureSnapshot(from: pasteboard)

        // 2. Re-focus target application if specified
        if let targetApp = targetApp {
            if #available(macOS 14.0, *) {
                targetApp.activate()
            } else {
                targetApp.activate(options: [.activateIgnoringOtherApps])
            }
            // Brief yield to allow window activation
            try? await Task.sleep(nanoseconds: 20_000_000) // 20ms
        }

        // 3. Stage text on pasteboard with transient tags
        let expectedChangeCount = stageTransientText(trimmed)

        // 4. Synthesize Cmd+V key event
        try postPasteKeystroke()

        // 5. Asynchronously restore user's previous clipboard after target app processes paste
        Task { [restoreDelayMs, pasteboard] in
            try? await Task.sleep(nanoseconds: restoreDelayMs * 1_000_000)
            Self.restoreSnapshot(snapshot, to: pasteboard, expectedChangeCount: expectedChangeCount)
        }
    }
}
